// 看板プロパティパネル
// =============================================================================

bool GuideSignEditor::drawEditPanel(RoadNetwork& network, PanelManager& panelManager,
                                     const RoadRenderer& renderer)
{
	if (m_editingSignId < 0) { panelManager.hide(U"guide_sign_edit"); return false; }
	GuideSignPlacement* gp = network.getGuideSign(m_editingSignId);
	if (!gp) { close(); panelManager.hide(U"guide_sign_edit"); return false; }
	auto& g = *gp;

	auto area = panelManager.beginContent(U"guide_sign_edit");
	if (!area) return false;

	PanelBuilder ui(static_cast<int>(panelManager.getSize(U"guide_sign_edit").x));
	bool dirty = false;

	// 種別
	ui.row(4, [&] {
		ui.label(U"種別:", ColorF{ 0.6 });
		if (ui.cycle(g.kind, kKindNames, 2, 130))
		{ g.autoGenerated = false; dirty = true; }
	});

	// 配置パラメータ
	if (drawPlacementRow(ui, g)) dirty = true;

	// プレビュー
	ui.spacer(4);
	const Vec2 pv = drawPreview(ui, g, renderer, panelManager, U"guide_sign_edit", 8.0);
	if (pv.y > 0) ui.spacer(static_cast<int>(pv.y) + 4);

	// 削除 / 編集ボタン
	ui.spacer(2);
	bool deleteRequested = false;
	ui.row(2, [&] {
		if (ui.button(U"削除", false, 60, U"この案内標識を削除"))
			deleteRequested = true;
	});
	if (deleteRequested)
	{
		network.removeGuideSign(m_editingSignId);
		close();
		panelManager.hide(U"guide_sign_editor");
		panelManager.hide(U"guide_sign_edit");
		ui.flush();
		panelManager.reportContentHeight(U"guide_sign_edit", ui.height());
		return true;
	}

	ui.spacer(2);
	if (ui.button(U"編集", false, 60, U"看板エディタを開く"))
	{
		m_draftElements      = g.elements;  // 空の場合はブランクキャンバスで開始
		m_draftValid         = true;
		m_selectedElement    = -1;
		m_draftTexDirty      = true;
		m_lastSelectedElement = -1;

		const Vec2 center{
			(Scene::Width()  - kEditorPanelInitialSize.x) * 0.5,
			(Scene::Height() - kEditorPanelInitialSize.y) * 0.5 };
		panelManager.show(U"guide_sign_editor",
			U"看板エディタ #{}"_fmt(m_editingSignId), center);
	}

	ui.flush();
	panelManager.reportContentHeight(U"guide_sign_edit", ui.height());
	return dirty;
}

