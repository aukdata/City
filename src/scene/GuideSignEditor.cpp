void GuideSignEditor::open(int signId, [[maybe_unused]] const RoadNetwork& network)
{
	m_editingSignId = signId;
}

void GuideSignEditor::close()
{
	m_editingSignId      = -1;
	m_selectedElement    = -1;
	m_dragging           = false;
	m_copyDrag           = false;
	m_draftElements.clear();
	m_draftValid         = false;
	m_draftTex           = RenderTexture{};
	m_draftTexDirty      = true;
	m_lastSelectedElement = -1;
}

