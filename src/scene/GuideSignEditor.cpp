// =============================================================================

bool GuideSignEditor::drawEdgeSection(PanelBuilder& ui, RoadEdge& edge,
                                      RoadNetwork& network, PanelManager& panelManager,
                                      const RoadRenderer& renderer)
{
	bool dirty = false;

	Array<int> myIds;
	for (const auto& g : network.guideSigns())
		if (g.id >= 0 && g.parentEdgeId == edge.id) myIds << g.id;

	static bool collapsed = true;
	ui.spacer(3);
	if (!ui.section(U"案内標識 ({})"_fmt(myIds.size()), collapsed, ColorF{ 0.7, 0.9, 1.0 }))
		return false;

	int deleteSignId = -1;

	for (const int signId : myIds)
	{
		GuideSignPlacement* gp = network.getGuideSign(signId);
		if (!gp) continue;
		auto& g = *gp;

		// 種別 + 編集 + 削除
		ui.row(3, [&] {
			if (ui.cycle(g.kind, kKindNames, 2, 100, U"種別を切替"))
			{ g.autoGenerated = false; dirty = true; }
			if (ui.button(U"編集", false, 40, U"エディタを開く"))
			{
				open(signId, network);
				panelManager.show(U"guide_sign_edit",
					U"案内標識 #{}"_fmt(signId), Vec2{ 20, 100 });
			}
			if (ui.button(U"削", false, 28)) deleteSignId = signId;
		});

		// 配置パラメータ
		if (drawPlacementRow(ui, g)) dirty = true;

		// プレビュー
		const Vec2 pv = drawPreview(ui, g, renderer, panelManager, U"edge_info", 8.0);
		if (pv.y > 0) ui.spacer(static_cast<int>(pv.y) + 2);
		ui.spacer(3);
	}

	// 新規追加ボタン
	const auto rb = RoadSign::roadbedExtentsOf(edge);
	const float leftLat  = rb.left  - GuideSign::kSideMargin_m;
	const float rightLat = rb.right + GuideSign::kSideMargin_m;
	const auto addSign = [&](int nodeId, float lat, GuideSignKind kind) {
		GuideSignPlacement gp;
		gp.parentEdgeId  = edge.id; gp.kind = kind; gp.nodeEndId = nodeId;
		gp.arcOffset     = (kind == GuideSignKind::DirectionArrow)
			? Min(GuideSign::kArrowPlaceArcOffset_m, edge.length * 0.7f)
			: GuideSign::kAutoPlaceArcOffset_m;
		gp.lateralOffset = lat;
		gp.poleHeight    = GuideSign::kPoleHeight_m;
		gp.autoGenerated = false;
		// elements は空のまま追加 → 編集パネルから看板エディタで要素を追加する
		network.addGuideSign(gp);
	};
	if (edge.nodeA >= 0)
	{
		ui.row(3, [&] {
			ui.label(U"A端:", ColorF{ 0.5 });
			if (ui.button(U"+距離", false, 50)) { addSign(edge.nodeA, leftLat, GuideSignKind::DirectionDistance); dirty = true; }
			if (ui.button(U"+方向", false, 50)) { addSign(edge.nodeA, leftLat, GuideSignKind::DirectionArrow); dirty = true; }
		});
	}
	if (edge.nodeB >= 0)
	{
		ui.row(3, [&] {
			ui.label(U"B端:", ColorF{ 0.5 });
			if (ui.button(U"+距離", false, 50)) { addSign(edge.nodeB, rightLat, GuideSignKind::DirectionDistance); dirty = true; }
			if (ui.button(U"+方向", false, 50)) { addSign(edge.nodeB, rightLat, GuideSignKind::DirectionArrow); dirty = true; }
		});
	}

	if (deleteSignId >= 0) { network.removeGuideSign(deleteSignId); dirty = true; }
	return dirty;
}

